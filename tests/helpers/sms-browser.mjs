import assert from 'node:assert/strict'
import {createUlid} from '../../src/core/shared/ids.ts'
import {accountSid,authToken,sendingNumber,smsRiderJourney} from './sms-journey.mjs'
export async function smsBrowser(page,h,journey,width,edge){
 await page.goto(h.origin+'/app/settings')
 await page.waitForFunction(()=>window.__TSR_ROUTER__?.state.location.pathname==='/app/settings')
 await page.getByText('Twilio SMS',{exact:true}).first().click()
 const section=page.getByRole('region',{name:'Twilio SMS settings'})
 await section.getByLabel('Twilio Account SID',{exact:true}).fill(accountSid)
 await section.getByLabel('Twilio Auth Token',{exact:true}).fill(authToken)
 await section.getByLabel('Sending number or Messaging Service',{exact:true}).fill(sendingNumber)
 const connected=page.waitForResponse(response=>response.url().endsWith('/sms/settings')&&response.request().method()==='PUT')
 await section.getByRole('button',{name:/Connect Twilio|Replace Twilio credentials/}).click()
 assert.equal((await connected).status(),200)
 await section.getByRole('status').filter({hasText:/Connected/}).waitFor()
 assert.equal(await section.getByLabel('Twilio Auth Token',{exact:true}).inputValue(),'','Secret is cleared after saving')
 assert.equal(await section.getByRole('status').innerText(),'Connected · A2P 10DLC: Campaign: VERIFIED, Brand: APPROVED (VERIFIED)','Settings shows the provider-verified campaign and brand')
 await journey.capture('sms-settings-registered')
 edge.setRegistered(false)
 await page.reload()
 await page.getByText('Twilio SMS',{exact:true}).first().click()
 await section.getByRole('status').filter({hasText:'No registered US A2P campaign found'}).waitFor()
 assert.equal(await section.getByRole('status').innerText(),'Connected · A2P 10DLC: No registered US A2P campaign found','Settings shows an unregistered sending number without claiming registration')
 await journey.capture('sms-settings-unregistered')
 edge.setRegistered(true)
 await page.goto(h.origin+'/app/automations')
 const panel=page.getByRole('region',{name:'Record automations'})
 await panel.getByLabel(/^Application/).selectOption(h.appId)
 await panel.getByLabel(/^Record type/).selectOption(h.entityId)
 await panel.getByRole('button',{name:'New automation',exact:true}).click()
 const form=page.getByRole('form',{name:'Automation definition'})
 await form.getByLabel('Automation name',{exact:true}).fill(`synthetic-cradle-106-sms-${width}`)
 await form.getByRole('combobox',{name:/^Action/}).selectOption('sms')
 await form.getByRole('combobox',{name:/^Phone field/}).selectOption(h.phoneLookupId)
 assert.equal(await form.getByRole('combobox',{name:/^Phone field/}).inputValue(),h.phoneLookupId,'Typed phone lookup can be selected')
 await form.getByRole('combobox',{name:/^Phone field/}).selectOption(h.phoneId)
 await form.getByRole('textbox',{name:/^SMS message/}).fill('Hello ')
 await form.getByRole('combobox',{name:/^Insert record value/}).selectOption(h.statusId)
 assert.equal(await form.getByRole('textbox',{name:/^SMS message/}).inputValue(),'Hello {{'+h.statusId+'}}')
 assert.deepEqual(await form.getByRole('combobox',{name:/^Phone field/}).locator('option').evaluateAll(options=>options.filter(option=>option.value).map(option=>option.value)),[h.phoneId,h.phoneLookupId],'SMS picker offers only typed phone fields and phone lookups')
 await journey.capture('sms-composed-action')
 const saved=page.waitForResponse(response=>response.url().endsWith('/api/user-automations')&&response.request().method()==='POST')
 await form.getByRole('button',{name:'Save automation',exact:true}).click()
 const response=await saved;assert.equal(response.status(),201)
 const automation=(await response.json()).data.result.value
 await h.request(`/api/user-automations/${automation.id}/disable`,{method:'POST',body:{commandId:createUlid(),version:automation.version}})
 const rider=await smsRiderJourney(h,edge)
 await page.goto(h.origin+rider.run.href)
 const run=page.locator(`#run-${rider.run.id}`)
 await run.getByText(`Twilio ${rider.refusal.code}: ${rider.refusal.message}`,{exact:true}).waitFor()
 assert.equal(await run.getByRole('button',{name:'Retry safe action'}).count(),0)
 await journey.capture('sms-registration-refusal')
 await page.goto(h.origin+'/app/settings');await page.getByText('Twilio SMS',{exact:true}).first().click()
 const replies=page.getByRole('region',{name:'Unattributed SMS replies'})
 for(const reply of rider.replies)await replies.getByText(reply.body,{exact:true}).first().waitFor()
 assert.ok(!(await replies.innerText()).includes('+15550100107'))
 await journey.capture('sms-unattributed-replies')
}
