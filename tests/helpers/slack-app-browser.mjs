import assert from 'node:assert/strict'
import {createUlid} from '../../src/core/shared/ids.ts'
import {signedSlack} from './slack-app-journey.mjs'
export async function slackAppBrowser(page,h,journey,width,edge){
 const root='/api/user-automations/slack',f=edge.fixture
 async function settings(){await page.goto(h.origin+'/app/settings');await page.waitForFunction(()=>window.__TSR_ROUTER__?.state.location.pathname==='/app/settings');await page.getByText('Slack app',{exact:true}).first().click()}
 await settings()
 const section=page.getByRole('region',{name:'Slack app settings',exact:true})
 await section.getByLabel('Slack client ID',{exact:true}).fill(f.clientId)
 await section.getByLabel('Slack client secret',{exact:true}).fill(f.clientSecret)
 await section.getByLabel('Slack signing secret',{exact:true}).fill(f.signingSecret)
 const configured=page.waitForResponse(response=>response.url().endsWith('/slack/settings')&&response.request().method()==='PUT')
 await section.getByRole('button',{name:/Save Slack credentials|Replace Slack credentials/}).click()
 assert.equal((await configured).status(),200)
 const authorization=new URL((await h.request(root+'/install',{method:'POST',body:{}})).data.authorizeUrl)
 const callback=await fetch(h.origin+'/oauth/slack/callback?'+new URLSearchParams({state:authorization.searchParams.get('state'),code:f.code}),{redirect:'manual',headers:{cookie:h.cookie}})
 assert.equal(callback.status,303);await callback.arrayBuffer()
 if((await h.request(root+'/settings')).data.linked)await h.request(root+'/link',{method:'DELETE',body:{}})
 await settings()
 await section.getByRole('status').filter({hasText:'Connected to'}).waitFor()
 assert.equal(await section.getByLabel('Slack client secret',{exact:true}).inputValue(),'')
 assert.equal(await section.getByLabel('Slack signing secret',{exact:true}).inputValue(),'')
 const issued=page.waitForResponse(response=>response.url().endsWith('/slack/link')&&response.request().method()==='POST')
 await section.getByRole('button',{name:'Link your Slack account',exact:true}).click()
 const link=(await (await issued).json()).data
 await signedSlack(h.origin,'/webhooks/slack/link',{team_id:f.teamId,user_id:f.ownerUserId,command:'/cradle-link',text:link.code})
 await section.getByRole('button',{name:'Refresh Slack link',exact:true}).click()
 await section.getByText('Your Slack account is linked to this Cradle account.',{exact:true}).waitFor()
 const previews=section.getByRole('region',{name:'Slack record-link previews',exact:true})
 await previews.getByRole('combobox',{name:/^Preview base/}).selectOption(h.appId)
 await previews.getByRole('combobox',{name:/^Preview table/}).selectOption(h.entityId)
 await previews.getByRole('checkbox',{name:'Status',exact:true}).check()
 const safe=page.waitForResponse(response=>response.url().endsWith('/slack/unfurl-fields')&&response.request().method()==='PUT')
 await previews.getByRole('button',{name:'Save preview fields',exact:true}).click()
 assert.equal((await safe).status(),200)
 assert.ok((await h.request(root+`/settings?appId=${h.appId}&entityId=${h.entityId}`)).data.unfurlSafeFieldIds.includes(h.statusId))
 await journey.capture('slack-app-settings')
 await page.goto(h.origin+'/app/automations')
 await page.waitForFunction(()=>window.__TSR_ROUTER__?.state.location.pathname==='/app/automations')
 const panel=page.getByRole('region',{name:'Record automations'})
 await panel.getByLabel(/^Application/).selectOption(h.appId)
 await panel.getByLabel(/^Record type/).selectOption(h.entityId)
 await panel.getByRole('button',{name:'New automation',exact:true}).click()
 const form=page.getByRole('form',{name:'Automation definition'})
 await form.getByLabel('Automation name',{exact:true}).fill(`synthetic-cradle-120-slack-${width}`)
 await form.getByRole('combobox',{name:/^Action/}).selectOption('slack-app')
 await form.getByRole('combobox',{name:/^Slack channel/}).selectOption(f.channelId)
 await form.getByRole('textbox',{name:/^Slack app message/}).fill('A record needs review')
 await form.getByRole('combobox',{name:/^Approval field/}).selectOption(h.statusId)
 await form.getByRole('group',{name:'Approve result',exact:true}).getByLabel(/^Status/).fill('approved')
 await form.getByRole('group',{name:'Reject result',exact:true}).getByLabel(/^Status/).fill('rejected')
 await journey.capture('slack-app-composed-action')
 const saved=page.waitForResponse(response=>response.url().endsWith('/api/user-automations')&&response.request().method()==='POST')
 await form.getByRole('button',{name:'Save automation',exact:true}).click()
 const response=await saved;assert.equal(response.status(),201)
 const automation=(await response.json()).data.result.value
 await h.request(`/api/user-automations/${automation.id}/disable`,{method:'POST',body:{commandId:createUlid(),version:automation.version}})
}
